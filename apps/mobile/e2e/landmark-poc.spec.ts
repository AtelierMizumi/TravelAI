import { test, expect } from '@playwright/test';
import { syntheticApi } from './fixtures/ux';
test.beforeEach(async ({ page }) => {
  await syntheticApi(page);
  await page.addInitScript(() => {
    const buffers = new Set<WebGLBuffer>();
    const create = WebGL2RenderingContext.prototype.createBuffer, remove = WebGL2RenderingContext.prototype.deleteBuffer;
    WebGL2RenderingContext.prototype.createBuffer = function() { const buffer = create.call(this); if (buffer) buffers.add(buffer); return buffer; };
    WebGL2RenderingContext.prototype.deleteBuffer = function(buffer) { if (buffer) buffers.delete(buffer); remove.call(this,buffer); };
    (window as any).livePocBuffers = () => buffers.size;
  });
});
