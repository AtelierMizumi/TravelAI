test('visibility pause, context loss fallback and touch rotation', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.goto('/destination/14'); await page.getByRole('button', { name: 'Mở mô hình 3D thử nghiệm' }).click();
  const canvas = page.getByLabel('Mô hình đình Việt Nam 3D'); await expect(canvas).toBeVisible();
  await expect(page.getByRole('status').filter({ hasText: '3D sẵn sàng' })).toBeVisible();
  await canvas.scrollIntoViewIfNeeded();
  const before = await canvas.getAttribute('data-camera');
  const bounds = (await canvas.boundingBox())!;
  const cdp = await page.context().newCDPSession(page);
  const point = { x: Math.round(bounds.x+bounds.width/2), y: Math.round(bounds.y+bounds.height/2) };
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [point] });
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: point.x+80, y: point.y }] });
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
  await expect(canvas).not.toHaveAttribute('data-camera', before!);
  await page.setViewportSize({ width: 700, height: 350 });
  await page.mouse.move(400, 220); await page.mouse.wheel(0, 8000);
  await expect(page.getByTestId('pavilion-host')).toHaveAttribute('data-rendering', 'paused');
  await canvas.scrollIntoViewIfNeeded();
  await expect(page.getByTestId('pavilion-host')).toHaveAttribute('data-rendering', 'on-demand');
  await page.evaluate(() => { Object.defineProperty(document, 'hidden', { configurable: true, get: () => true }); document.dispatchEvent(new Event('visibilitychange')); });
  await expect(page.getByTestId('pavilion-host')).toHaveAttribute('data-rendering', 'paused');
  const frames = await canvas.getAttribute('data-frames');
  await page.getByRole('button', { name: 'Xoay phải' }).click();
  expect(await canvas.getAttribute('data-frames')).toBe(frames);
  await page.evaluate(() => { Object.defineProperty(document, 'hidden', { configurable: true, get: () => false }); document.dispatchEvent(new Event('visibilitychange')); });
  await expect(canvas).not.toHaveAttribute('data-frames', frames!);
  await canvas.evaluate(el => (el as HTMLCanvasElement).getContext('webgl2')!.getExtension('WEBGL_lose_context')!.loseContext());
  await expect(page.getByRole('alert').filter({ hasText: 'Không thể mở 3D' })).toBeVisible();
  await expect(page.getByAltText('Ảnh thay thế cho mô hình 3D')).toBeVisible();
  expect(await page.evaluate(() => (window as any).livePocBuffers())).toBe(0);
});
